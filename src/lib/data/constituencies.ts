/**
 * Returns available constituencies for a state, or generates a comprehensive fallback list.
 */
export function getConstituenciesForState(stateCode: string): AssemblyConstituency[] {
  const normalized = (stateCode || '').trim().toUpperCase();
  if (STATE_CONSTITUENCIES[normalized]) {
    return STATE_CONSTITUENCIES[normalized];
  }

  // Fallback: Generate standardized ECI numbered assembly constituencies for any state (1 to 60)
  return Array.from({ length: 60 }, (_, i) => ({
    acNumber: i + 1,
    nameEn: `Constituency AC-${i + 1}`,
    nameHi: `निर्वाचन क्षेत्र एसी-${i + 1}`,
  }));
}
